// laravel/scripts/check-source-allowlist.mjs
//
// CI guard for resources/css/app.css's Tailwind v4 `@source`/`@source not` allow-list (`source(none)`
// mode — see the long comment at the top of app.css). Two silent-drift failure modes this exists to
// catch, both raised in the review this answers:
//
//   1. The allow-list itself gets loosened (a `@source not` exclusion removed, or a glob widened).
//      Spec/fixture files (PatientFlags.spec.js's RAW_STATUS_TEXT, ConfirmDialog.test.js's literal
//      `'hover:bg-danger-600'`) hold full utility strings on purpose, relying on `__tests__` staying
//      excluded — if that exclusion is ever removed, those strings would start shipping dead rules
//      into production, with no failing test to notice.
//   2. The reverse: a component's only real-world use of a class quietly disappears (edited or
//      deleted) while a test fixture keeps spelling the same string. The utility silently stops
//      shipping — no test reddens, because nothing asserts what the compiled CSS actually contains.
//
// Both failure modes are "the compiled class set changed and nobody meant it to" — so the cheapest
// reliable guard is a snapshot of the class set the CURRENT build actually emits (read from the real,
// already-built CSS via public/build/manifest.json — never `ls app-*.css`; there are two, and only
// the manifest says which one is live), diffed against the SNAPSHOT committed below. Any diff, either
// direction, fails CI. A deliberate, reviewed UI change updates the snapshot with:
//   npm run build && node scripts/check-source-allowlist.mjs --write
//
// Lives under scripts/ — deliberately NOT one of app.css's `@source` targets (verified: adding this
// file and rebuilding changes nothing in the emitted class set — see the PART C verification that
// shipped alongside this script), so spelling real utility class names in SNAPSHOT below is inert.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const laravelRoot = path.resolve(here, '..');

const manifestPath = path.join(laravelRoot, 'public/build/manifest.json');
if (!fs.existsSync(manifestPath)) {
    console.error('public/build/manifest.json not found — run `npm run build` first.');
    process.exit(1);
}
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const cssFile = manifest['resources/css/app.css']?.file;
if (!cssFile) {
    console.error('Could not resolve resources/css/app.css from public/build/manifest.json.');
    process.exit(1);
}
const css = fs.readFileSync(path.join(laravelRoot, 'public/build', cssFile), 'utf8');

/** Escape-aware split: only split `s` on a TOP-LEVEL, unescaped comma. A literal `\,` inside an
 *  arbitrary value (`grid-cols-[auto,1fr]` compiles to `.grid-cols-\[auto\,1fr\]`) must NOT split —
 *  a naive `.split(',')` truncates that selector into garbage (caught while building this guard). */
function splitUnescaped(s) {
    const parts = [];
    let cur = '';
    for (let i = 0; i < s.length; i++) {
        const c = s[i];
        if (c === '\\' && i + 1 < s.length) { cur += c + s[i + 1]; i++; continue; }
        if (c === ',') { parts.push(cur); cur = ''; continue; }
        cur += c;
    }
    parts.push(cur);
    return parts;
}

/** Pull every simple class selector (`.foo`, `.hover\:bg-brand-50\/40`, …) out of compiled CSS.
 *  Deliberately excludes compound/descendant selectors (space, unescaped extra `.`, combinators) —
 *  those are hand-written rules (e.g. the driver.js popover theming block), not Tailwind utilities. */
function extractClasses(cssText) {
    const classes = new Set();
    const re = /[{};]([^{};]*)\{/g;
    const padded = ';' + cssText;
    let m;
    while ((m = re.exec(padded))) {
        for (const raw of splitUnescaped(m[1])) {
            const sel = raw.trim();
            if (!sel.startsWith('.')) continue;
            let bad = false;
            let end = sel.length;
            for (let i = 1; i < sel.length; i++) {
                const c = sel[i];
                if (c === '\\') { i++; continue; }
                if (c === ' ' || c === '.' || c === '>' || c === '~' || c === '+') { bad = true; break; }
                if (c === ':') { end = i; break; }
            }
            if (bad) continue;
            const cls = sel.slice(0, end);
            if (cls.length > 1) classes.add(cls);
        }
    }
    return classes;
}

